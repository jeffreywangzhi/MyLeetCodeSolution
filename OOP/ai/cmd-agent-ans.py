import os
import json
from openai import OpenAI

# 1. Define local system functions
def list_files(directory="."):
    """Returns a list of files in the specified directory."""
    try:
        files = os.listdir(directory)
        return json.dumps({"status": "success", "files": files})
    except Exception as e:
        return json.dumps({"status": "error", "message": str(e)})

def read_file(filepath):
    """Reads and returns the contents of a file."""
    try:
        with open(filepath, 'r') as f:
            content = f.read()
        return json.dumps({"status": "success", "content": content})
    except Exception as e:
         return json.dumps({"status": "error", "message": str(e)})

def write_file(filepath, content):
    """Writes content to a specific file."""
    # SECURITY GUARD: Always ask human before modifying files
    print(f"\n[⚠️ SECURITY ALERT] The AI wants to write to: {filepath}")
    confirm = input("Allow this action? (y/n): ")
    if confirm.lower() != 'y':
        return json.dumps({"status": "error", "message": "User denied the write operation."})
    
    try:
        with open(filepath, 'w') as f:
            f.write(content)
        return json.dumps({"status": "success", "message": f"Successfully wrote to {filepath}"})
    except Exception as e:
        return json.dumps({"status": "error", "message": str(e)})

# Map available tools to their Python functions
available_functions = {
    "list_files": list_files,
    "read_file": read_file,
    "write_file": write_file
}

# 2. Define the Tool schemas for the LLM
tools = [
    {
        "type": "function",
        "function": {
            "name": "list_files",
            "description": "Lists all files and folders in a specified directory.",
            "parameters": {
                "type": "object",
                "properties": {
                    "directory": {
                        "type": "string",
                        "description": "The directory path to list files from. Default is '.' for current directory."
                    }
                }
            }
        }
    },
    {
        "type": "function",
        "function": {
            "name": "read_file",
            "description": "Reads the text content of a specified file.",
            "parameters": {
                "type": "object",
                "properties": {
                    "filepath": {
                        "type": "string",
                        "description": "The path to the file to read."
                    }
                },
                "required": ["filepath"]
            }
        }
    },
    {
        "type": "function",
        "function": {
            "name": "write_file",
            "description": "Writes provided text content to a specified file. Overwrites if it exists.",
            "parameters": {
                "type": "object",
                "properties": {
                    "filepath": {
                        "type": "string",
                        "description": "The path to the file to write to."
                    },
                    "content": {
                        "type": "string",
                        "description": "The text content to write into the file."
                    }
                },
                "required": ["filepath", "content"]
            }
        }
    }
]

# 3. Core execution loop
def main():
    # Initialize client (automatically pulls from OPENAI_API_KEY environment variable)
    client = OpenAI()
    
    messages = [
        {
            "role": "system", 
            "content": "You are a helpful terminal assistant. Use the provided tools to interact with the user's file system safely. Answer concisely."
        }
    ]
    
    print("🤖 AI Terminal Agent initialized. Type 'exit' to quit.")
    
    while True:
        try:
            user_input = input("\nAgent> ")
            if user_input.lower() in ['exit', 'quit']:
                break
                
            messages.append({"role": "user", "content": user_input})
            
            # Step A: Send prompt and available tools to the LLM
            response = client.chat.completions.create(
                model="gpt-4o-mini",
                messages=messages,
                tools=tools,
                tool_choice="auto"
            )
            
            response_message = response.choices[0].message
            messages.append(response_message)
            
            # Step B: Check if the LLM wants to call a tool
            if response_message.tool_calls:
                for tool_call in response_message.tool_calls:
                    function_name = tool_call.function.name
                    # Parse the JSON arguments generated by the model
                    function_args = json.loads(tool_call.function.arguments)
                    
                    print(f"[⚙️ Executing tool: {function_name}({function_args})]")
                    
                    # Execute the actual Python function locally
                    function_to_call = available_functions.get(function_name)
                    if function_to_call:
                        function_response = function_to_call(**function_args)
                        
                        # Step C: Send the function's result back to the LLM
                        messages.append({
                            "tool_call_id": tool_call.id,
                            "role": "tool",
                            "name": function_name,
                            "content": function_response,
                        })
                        
                # Get the final natural language summary from the LLM
                final_response = client.chat.completions.create(
                    model="gpt-4o-mini",
                    messages=messages
                )
                
                final_message = final_response.choices[0].message
                messages.append(final_message)
                print(f"\n{final_message.content}")
                
            else:
                # No tools called; print standard text response
                if response_message.content:
                    print(f"\n{response_message.content}")
                    
        except KeyboardInterrupt:
            break
        except Exception as e:
            print(f"\nError: {e}")

if __name__ == "__main__":
    main()